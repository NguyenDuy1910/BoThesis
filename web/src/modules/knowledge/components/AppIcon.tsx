const fallbackGlyphs = {
  upload: FileUp,
  web: Globe,
  unknown: Plug,
} as const;

export type AppIconFallback = keyof typeof fallbackGlyphs;

export function AppIcon({
  /** Connector key or provider display name; both resolve to the same mark. */
  connector,
  size = "md",
  fallback = "unknown",
  className,
}: {
  connector: string;
  size?: "sm" | "md";
  fallback?: AppIconFallback;
  className?: string;
}) {
  const key = marks[connector] ? connector : connectorKeyFor(connector);
  const Mark = marks[key];
  const Glyph = fallbackGlyphs[fallback];

  return (
    <span
      aria-hidden="true"
      className={cn("knowledge-app-icon", size === "sm" && "knowledge-app-icon--sm", className)}
    >
      {Mark ? <Mark className="knowledge-app-icon__mark" /> : <Glyph className="knowledge-app-icon__glyph" />}
    </span>
  );
}
